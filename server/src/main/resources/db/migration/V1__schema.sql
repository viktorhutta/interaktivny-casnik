CREATE TABLE category (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL,
    display_order integer NOT NULL,
    archived boolean NOT NULL DEFAULT false
);

CREATE TABLE menu_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id bigint NOT NULL REFERENCES category (id),
    name varchar(100) NOT NULL,
    description varchar(255) NOT NULL,
    price numeric(8, 2) NOT NULL,
    available boolean NOT NULL DEFAULT true,
    archived boolean NOT NULL DEFAULT false
);

CREATE TABLE ingredient (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL,
    available boolean NOT NULL DEFAULT true,
    archived boolean NOT NULL DEFAULT false
);

CREATE TABLE menu_item_ingredient (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_item_id bigint NOT NULL REFERENCES menu_item (id),
    ingredient_id bigint NOT NULL REFERENCES ingredient (id),
    type varchar(20) NOT NULL,
    removable boolean NOT NULL,
    extra_price numeric(8, 2),
    UNIQUE (menu_item_id, ingredient_id)
);

CREATE TABLE dining_table (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label varchar(20) NOT NULL UNIQUE,
    token varchar(64) NOT NULL
);

CREATE TABLE table_account (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dining_table_id bigint NOT NULL REFERENCES dining_table (id),
    status varchar(20) NOT NULL,
    payment_method varchar(20),
    gateway_payment_id bigint,
    created_at timestamp NOT NULL,
    closed_at timestamp
);

CREATE TABLE waiter_call (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_account_id bigint NOT NULL REFERENCES table_account (id),
    created_at timestamp NOT NULL,
    resolved boolean NOT NULL DEFAULT false
);

CREATE TABLE staff_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    password_hash varchar(100) NOT NULL,
    role varchar(20) NOT NULL
);

CREATE TABLE customer_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_account_id bigint NOT NULL REFERENCES table_account (id)
);

CREATE TABLE order_status_change (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_order_id bigint NOT NULL REFERENCES customer_order (id),
    status varchar(20) NOT NULL,
    changed_at timestamp NOT NULL,
    staff_user_id bigint REFERENCES staff_user (id)
);

CREATE TABLE order_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_order_id bigint NOT NULL REFERENCES customer_order (id),
    menu_item_id bigint NOT NULL REFERENCES menu_item (id),
    name varchar(100) NOT NULL,
    quantity integer NOT NULL,
    price numeric(8, 2) NOT NULL
);

CREATE TABLE order_item_ingredient (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id bigint NOT NULL REFERENCES order_item (id),
    ingredient_id bigint NOT NULL REFERENCES ingredient (id),
    change_type varchar(20) NOT NULL,
    name varchar(50) NOT NULL,
    price numeric(8, 2) NOT NULL
);